const FACES: Rank[] = ["J", "Q", "K"];

export function findCardCombos(cards: Card[]): Combo[] {
  const combos: Combo[] = [];
  const n = cards.length;
  if (n < 2) return combos;

  // 1) สีแดง/ดำ
  const red = cards.filter((c) => SUITS[c.suit].red).length;
  if (red === n) combos.push({ title: "ไพ่แดงทุกใบ", text: "เรื่องนี้ไหลลื่น คนรอบตัวเป็นใจ เป็นจังหวะดีที่จะเดินหน้า", source: "cartomancy" });
  else if (red === 0) combos.push({ title: "ไพ่ดำทุกใบ", text: "เรื่องนี้มีอุปสรรคและต้องใช้ความพยายามมาก ค่อย ๆ ทำอย่างรอบคอบ", source: "cartomancy" });

  // 2) ไพ่หน้าเดียวกัน
  const ranks = new Map<Rank, number>();
  for (const c of cards) ranks.set(c.rank, (ranks.get(c.rank) ?? 0) + 1);
  for (const [rank, c] of ranks) {
    if (c >= 2) combos.push({ title: `${rank} ออก ${c} ใบ`, text: SAME_RANK[rank][c >= 3 ? 1 : 0], source: "cartomancy" });
  }

  // 3) ไพ่หน้าคน
  const faces = cards.filter((c) => FACES.includes(c.rank)).length;
  if (faces >= 2) combos.push({ title: `ไพ่หน้าคน ${faces} ใบ`, text: "เรื่องนี้ขึ้นอยู่กับคนรอบตัวมาก ใครที่เข้ามาช่วงนี้มีผลต่อผลลัพธ์", source: "cartomancy" });

  // 4) ดอกคู่กัน
  const suits = new Set(cards.map((c) => c.suit));
  for (const [a, b, text] of SUIT_PAIRS) {
    if (suits.has(a) && suits.has(b)) combos.push({ title: `${SUITS[a].name} + ${SUITS[b].name}`, text, source: "cartomancy" });
  }

  // 5) Q กับ K ดอกเดียวกัน = คู่ครอง
  for (const suit of suits) {
    if (cards.some((c) => c.suit === suit && c.rank === "Q") && cards.some((c) => c.suit === suit && c.rank === "K")) {
      combos.push({ title: `Q กับ K ${SUITS[suit].name}`, text: "คู่ชายหญิงที่อยู่ข้างกัน หมายถึงคู่ครองหรือคู่ที่ช่วยเหลือกัน", source: "cartomancy" });
    }
  }

  return combos;
}
