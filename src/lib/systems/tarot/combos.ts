const LABEL = (id: string) => TAROT_DECK.find((c) => c.id === id)!.nameTh;

export function findTarotCombos(spread: TarotSpread, cards: DrawnTarot[]): Combo[] {
  const combos: Combo[] = [];
  const n = cards.length;
  if (n < 2) return combos;

  // 1) ไพ่กลุ่มเดียวกันออกเกินครึ่ง (Book T: "a majority of …")
  if (n >= 3) {
    const groups: Record<string, number> = {};
    for (const { card } of cards) {
      const key = card.arcana === "major" ? "major" : card.suit!;
      groups[key] = (groups[key] ?? 0) + 1;
      if (card.number >= 11) groups.court = (groups.court ?? 0) + 1;
    }
    for (const [key, c] of Object.entries(groups)) {
      if (c * 2 <= n) continue;
      const name = key === "major" ? "ไพ่ใบใหญ่ (Major Arcana)" : key === "court" ? "ไพ่ราชสำนัก (คน)" : `ชุด${TAROT_SUITS[key as TarotSuit].nameTh}`;
      combos.push({ title: `${name} ออก ${c} จาก ${n} ใบ`, text: MAJORITY[key as keyof typeof MAJORITY], source: "book-t" });
    }
  }

  // 2) ตัวเลขเดียวกันหลายใบ (เฉพาะไพ่ชุดเล็ก)
  const ranks = new Map<number, number>();
  for (const { card } of cards) if (card.arcana === "minor") ranks.set(card.number, (ranks.get(card.number) ?? 0) + 1);
  for (const [rank, c] of ranks) {
    if (c >= 3) {
      const [four, three] = BOOK_T_RANKS[rank];
      combos.push({ title: `${RANK_NAME[rank]} ${c} ใบ`, text: c >= 4 ? four : three, source: "book-t" });
    } else if (c === 2) {
      combos.push({ title: `${RANK_NAME[rank]} 2 ใบ`, text: `ตัวเลขซ้ำเน้นเรื่อง${NUMBER_THEME[rank]}`, source: "modern" });
    }
  }

  // 3) ธาตุของไพ่ที่วางติดกัน (Book T elemental dignities)
  //    Celtic Cross ดูคู่ที่วางทับกัน (ใบ 1–2) ส่วนแบบอื่นดูใบที่อยู่ติดกันตามลำดับ
  const neighbours: [number, number][] = spread.id === "celtic" ? [[0, 1]] : cards.slice(1).map((_, i) => [i, i + 1]);
  for (const [i, j] of neighbours) {
    const a = cards[i];
    const b = cards[j];
    if (!a.card.suit || !b.card.suit) continue;
    const pair = `${a.card.nameTh} (${a.position.name}) กับ ${b.card.nameTh} (${b.position.name})`;
    if (a.card.suit === b.card.suit) {
      combos.push({ title: `ธาตุเดียวกันเสริมกำลัง`, text: `${pair} เป็นธาตุ${TAROT_SUITS[a.card.suit].element}เหมือนกัน ความหมายของทั้งสองใบจึงแรงขึ้น`, source: "book-t" });
    } else if (isContrary(a.card.suit, b.card.suit)) {
      combos.push({
        title: `ธาตุตรงข้ามทอนกำลัง`,
        text: `${pair} เป็นธาตุ${TAROT_SUITS[a.card.suit].element}กับธาตุ${TAROT_SUITS[b.card.suit].element}ซึ่งขัดกัน ความหมายของทั้งสองใบจึงเบาลง ทั้งด้านดีและด้านร้าย`,
        source: "book-t",
      });
    }
  }

  // 4) คู่ไพ่ที่มีความหมายพิเศษ
  const ids = new Set(cards.map((c) => c.card.id));
  for (const [a, b, title, text] of PAIRS) {
    if (ids.has(a) && ids.has(b)) combos.push({ title, text, source: "modern" });
  }

  // 5) ทิศทางของเรื่อง: อดีต → อนาคต
  if (spread.id === "three") {
    const [past, , future] = cards;
    if (past.reversed && !future.reversed) {
      combos.push({ title: "จากติดขัดสู่คลี่คลาย", text: `ไพ่อดีตกลับหัวแต่ไพ่อนาคตตั้ง (${LABEL(past.card.id)} → ${LABEL(future.card.id)}) เรื่องนี้กำลังดีขึ้นเรื่อย ๆ`, source: "modern" });
    } else if (!past.reversed && future.reversed) {
      combos.push({ title: "พลังเริ่มแผ่ว", text: `ไพ่อดีตตั้งแต่ไพ่อนาคตกลับหัว (${LABEL(past.card.id)} → ${LABEL(future.card.id)}) ระวังอย่าปล่อยให้สิ่งที่เคยดีค่อย ๆ หลุดมือ`, source: "modern" });
    }
  }

  return combos;
}
