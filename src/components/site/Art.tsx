import manifest from "@/lib/art-manifest.json";

// Plain <img> tags don't get Next's basePath, so add it for sub-path deploys (GitHub Pages)
const BASE_PATH = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

type ArtName = keyof typeof manifest;

export function artSrcSet(name: ArtName): string {
  const a = manifest[name];
  return a.widths.map((w) => `${BASE_PATH}/art/${name}-${w}.webp ${w}w`).join(", ");
}

export function artSrc(name: ArtName): string {
  const a = manifest[name];
  return `${BASE_PATH}/art/${name}-${a.widths[0]}.webp`;
}

interface Props {
  name: string;
  /** "" for decorative images */
  alt: string;
  sizes: string;
  className?: string;
  priority?: boolean;
}

/** Responsive artwork from public/art (generated by scripts/prepare-site-images.mjs) */
export function ArtImage({ name, alt, sizes, className, priority }: Props) {
  const key = name as ArtName;
  const a = manifest[key];
  return (
    // eslint-disable-next-line @next/next/no-img-element -- static export with pre-sized WebP variants
    <img
      src={artSrc(key)}
      srcSet={artSrcSet(key)}
      sizes={sizes}
      width={a.width}
      height={a.height}
      alt={alt}
      loading={priority ? "eager" : "lazy"}
      fetchPriority={priority ? "high" : undefined}
      decoding="async"
      className={className}
    />
  );
}
